-- 1. Create table for KU Custom Synonyms & Thai translations
CREATE TABLE IF NOT EXISTS public.ku_synonyms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_id TEXT NOT NULL,
    synonym_text TEXT NOT NULL,
    lang_tag TEXT DEFAULT 'ku',
    status TEXT DEFAULT 'approved' CHECK (status IN ('pending', 'approved', 'rejected')),
    suggested_by_name TEXT,
    suggested_by_email TEXT,
    reviewer_notes TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()),
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- Index for fast concept lookup and search
CREATE INDEX IF NOT EXISTS idx_ku_synonyms_cid ON public.ku_synonyms(concept_id);
CREATE INDEX IF NOT EXISTS idx_ku_synonyms_status ON public.ku_synonyms(status);
CREATE INDEX IF NOT EXISTS idx_ku_synonyms_text ON public.ku_synonyms(synonym_text);

-- Prevent exact duplicate for same concept and text
CREATE UNIQUE INDEX IF NOT EXISTS idx_ku_synonyms_unique ON public.ku_synonyms(concept_id, LOWER(TRIM(synonym_text)));

-- 2. Create table for Release History (Handover to KAHIS)
CREATE TABLE IF NOT EXISTS public.release_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version TEXT NOT NULL,
    total_terms INT DEFAULT 42299,
    total_ku_synonyms INT DEFAULT 0,
    file_name TEXT,
    file_size_bytes BIGINT,
    file_url TEXT,
    release_notes TEXT,
    created_by TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- 3. Row Level Security (RLS)
ALTER TABLE public.ku_synonyms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.release_history ENABLE ROW LEVEL SECURITY;

-- Allow public read of approved synonyms
DROP POLICY IF EXISTS "Allow read approved synonyms" ON public.ku_synonyms;
CREATE POLICY "Allow read approved synonyms" 
ON public.ku_synonyms FOR SELECT 
USING (status = 'approved');

-- Allow anyone to suggest a synonym (with status 'pending')
DROP POLICY IF EXISTS "Allow insert pending suggestions" ON public.ku_synonyms;
CREATE POLICY "Allow insert pending suggestions" 
ON public.ku_synonyms FOR INSERT 
WITH CHECK (status = 'pending');

-- Allow read release history
DROP POLICY IF EXISTS "Allow read releases" ON public.release_history;
CREATE POLICY "Allow read releases" 
ON public.release_history FOR SELECT 
USING (true);

